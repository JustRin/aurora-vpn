//! Veil — собственный туннель Aurora VPN.
//!
//! Снаружи это обычный браузер на обычном сайте. Клиент открывает TLS 1.3 с
//! отпечатком Chrome на домен, у которого настоящий сертификат и настоящий сайт
//! (Caddy или nginx на 443), договаривается о h2 и держит одно соединение, как
//! вкладка. Каждое проксируемое соединение — отдельный POST-поток внутри него.
//! Кто пришёл без жетона, получает сайт: проба ТСПУ не отличит сервер от
//! любого другого хостинга с сайтом.
//!
//! Поток туннеля:
//! ```text
//! POST {path}                    cookie: _sid=base64url(nonce16 | ts64 | hmac16)
//! тело запроса  → записи клиента (ключ up)
//! тело ответа   ← записи сервера (ключ down), статус 200
//! запись = len16 | ChaCha20-Poly1305( тип8 | длина16 | данные | набивка )
//! ```
//! Первая запись клиента — `HEADER`: команда (1 TCP, 3 UDP) и адрес в формате
//! SOCKS5. Дальше `DATA`. Для UDP каждая запись — один датаграм с адресом
//! впереди. Ключи потока выводятся из пароля и nonce жетона, поэтому повтор
//! жетона сервер отвергает, а промежуточный фронт (CDN, реле в РФ) видит только
//! шифротекст.

